## Library importation.
import numpy as np                                                                                                                      # Core numerical operations.

from typing import Iterator                                                                                                             # Typing for iteration unpacking.
from dataclasses import dataclass                                                                                                       # Dataclass structure definition.

@dataclass
class SolverResult:
    """
    Standardized return object for mGFD PDE solvers.
    
    This dataclass encapsulates the numerical approximation and the spatial topology 
    (neighbor list) generated by the Generalized Finite Difference (GFD) stencils. 
    It is designed to support 1D solutions for stationary problems and 2D solutions 
    for transient problems, while tracking the performance and convergence state 
    of the underlying Krylov subspace solvers (e.g., BiCGStab, GMRES).

    Supports unpacking for backward compatibility (u_ap, vec = result).
    
    Attributes:
        solution        m x t           ndarray         The computed approximation solution.
        neighbors       m x nvec        ndarray         The corresponding neighbor list.
        converged                       bool            True if the linear solver successfully converged.
        compute_time                    float           Time in seconds that the solver took to execute.
    """
    solution: np.ndarray                                                                                                                # Mathematical solution generated by the solver.
    neighbors: np.ndarray                                                                                                               # Computed spatial neighborhood list.
    converged: bool = True                                                                                                              # Convergence success flag.
    compute_time: float = 0.0                                                                                                           # Performance clock time.

    def __iter__(self) -> Iterator[np.ndarray]:
        """
        Allows backward-compatible unpacking of the result.
        
        This generator enables older scripts to cleanly extract the solution and neighbor list 
        as if the solver returned a standard tuple (u_ap, vec = solver(...)), ensuring zero 
        breaking changes when migrating from raw tuples to the SolverResult architecture.
        
        Yields:
        solution    ndarray     The primary solution matrix.
        neighbors   ndarray     The spatial neighborhood matrix.
        """
        yield self.solution                                                                                                             # Yield mathematical solution as first element.
        yield self.neighbors                                                                                                            # Yield neighborhood array as second element.
